#   default_category : 분류 규칙에 아무것도 안 걸릴 때 쓰는 기본 카테고리 (null 가능)
#   force_category   : 있으면 무조건 이 카테고리 (외부기관 게시판용)
# 추가는 tools/add_board.py 를 쓰거나 boards.json 을 직접 편집.
# ---------------------------------------------------------------------------
import json as _json
from pathlib import Path as _Path

BOARDS_FILE = _Path(__file__).resolve().parent.parent / "boards.json"


def _load_boards():
    with open(BOARDS_FILE, encoding="utf-8") as f:
        data = _json.load(f)
    boards = data["boards"] if isinstance(data, dict) else data
    for b in boards:
        b.setdefault("unit", None)
        b.setdefault("college", None)
        b.setdefault("default_category", None)
    return [b for b in boards if not b.get("disabled")]


